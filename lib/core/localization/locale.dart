/// `t('key')` accessor scoped to the current [AppLocale], read from an
/// [InheritedWidget] set up in `app.dart` so screens never poke `AppState`
/// directly just to read strings.
class AppStringsScope extends InheritedWidget {
  const AppStringsScope({
    super.key,
    required this.locale,
    required super.child,
  });

  final AppLocale locale;

  static AppStringsScope of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<AppStringsScope>();
    assert(scope != null, 'AppStringsScope not found in context');
    return scope!;
  }

  /// Falls back to English for keys not translated yet, then to the key.
  String call(String key) =>
      AppStrings.forLocale(locale)[key] ?? AppStrings.en[key] ?? key;

  @override
  bool updateShouldNotify(AppStringsScope oldWidget) =>
      oldWidget.locale != locale;
}

extension AppStringsContext on BuildContext {
  /// Usage: `context.t('planJourney')`.
  String t(String key) => AppStringsScope.of(this)(key);

  /// [t] with `{name}` placeholders filled in, e.g.
  /// `context.tf('statSubmittedA11y', {'n': 14})`.
  String tf(String key, Map<String, Object> args) => fillTemplate(t(key), args);
}

/// Replaces each `{name}` in [template] with `args[name]`.
String fillTemplate(String template, Map<String, Object> args) {
  var result = template;
  args.forEach(
    (name, value) => result = result.replaceAll('{$name}', '$value'),
  );
  return result;
}
